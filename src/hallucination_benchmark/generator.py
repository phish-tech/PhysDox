#!/usr/bin/env python3
"""
Hardware-Grounded Hallucination Benchmark Generator
=====================================================
LLM-assisted, rule-validated pipeline for constructing sabotage benchmarks.

Pipeline:
  Phase 1: Load seed data (constraints + domains)
  Phase 2: Generate correct protocols
  Phase 3: Inject minimal sabotage (one constraint violation per item)
  Phase 4: Rule-based validation
  Phase 5: LLM verification (plausibility, ambiguity, obviousness)
  Phase 6: Mix in valid + ambiguous negative samples, assign difficulty
  Phase 7: Output benchmark.json + manifest.json

Usage:
  python3 generator.py
  python3 generator.py --rounds 5 --protocols-per-domain 5
  python3 generator.py --seed-data ./my_seed --output ./my_output
  python3 generator.py --model deepseek
  python3 generator.py --concurrency 8
"""

