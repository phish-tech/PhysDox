# ============================================================
# Rule-based sabotage fallback (regex parameter substitution)
# ============================================================

def _rule_based_sabotage(correct_protocol: str, constraint_key: str, constraint_info: dict) -> dict | None:
    """Apply rule-based sabotage when LLM fails.

    Uses regex to find and modify specific parameters in the protocol text.
    Returns dict with sabotage result, or None if no applicable pattern found.
    """
    sabo = correct_protocol
    what_changed = ""

    if constraint_key == "sampling_theorem":
        patterns = [
            (r"(\d+(?:\.\d+)?)\s*MSPS", lambda m: f"{float(m.group(1))/100:.0f} kSPS"),
            (r"(\d+(?:\.\d+)?)\s*(?:Hz|SPS)\s*(?:sampling|sample)", lambda m: f"{float(m.group(1))/100:.0f} Hz sampling"),
            (r"samples?\s*at\s*(\d+(?:\.\d+)?)\s*(?:Hz|kSPS|MSPS)", lambda m: f"samples at {float(m.group(1))/100:.0f} kSPS"),
        ]
        for pat, repl in patterns:
            new = re.sub(pat, repl, sabo, count=1, flags=re.I)
            if new != sabo:
                sabo = new
                what_changed = "Reduced ADC sampling rate by 100x, violating Nyquist theorem"
                break

    elif constraint_key == "ematerial_block":
        if "radar" in sabo.lower():
            insert_pats = [
                r"(positioned?\s+\d+\.?\d*\s*(?:m|meter|cm)[^.]*?\.)",
                r"(subject[^.]*?chest[^.]*?\.)",
                r"(The\s+radar\s+[^.]*?\.)",
            ]
            for pat in insert_pats:
                m = re.search(pat, sabo, re.I)
                if m:
                    sabo = sabo[:m.end()] + " A 5mm thick aluminum plate is placed between the radar and the subject for electromagnetic shielding." + sabo[m.end():]
                    what_changed = "Inserted aluminum plate between radar and subject, blocking mmWave signal"
                    break

    elif constraint_key == "anatomical_misplacement":
        if "emg" in sabo.lower() or "gesture" in sabo.lower():
            replacements = [
                (r"forearm", "lower leg (calf)"),
                (r"flexor\s*carpi\s*ulnaris", "tibialis anterior"),
                (r"extensor\s*carpi\s*radialis", "gastrocnemius"),
                (r"first\s*dorsal\s*interosseous", "peroneus longus"),
            ]
            for pat, repl in replacements:
                new = re.sub(pat, repl, sabo, count=1, flags=re.I)
                if new != sabo:
                    sabo = new
                    what_changed = "Moved sEMG electrodes from forearm to leg muscles"
                    break
        if "throat" in sabo.lower() or "speech" in sabo.lower():
            new = re.sub(r"thyroid\s*cartilage|throat|laryn", "olecranon process of the elbow", sabo, count=1, flags=re.I)
            if new != sabo:
                sabo = new
                what_changed = "Moved throat microphone to elbow"

    elif constraint_key == "accuracy_impossibility":
        patterns = [
            (r"(<|±|MAE\s*(?:of\s*)?)(\d+\.?\d*)\s*(bpm|mmHg|breaths/min)",
             lambda m: f"{m.group(1)}0.0{m.group(2)} {m.group(3)}"),
            (r"(\d{2,3}\.?\d*)%?\s*(?:accuracy|classification accuracy|recognition accuracy)",
             lambda m: "99.99% accuracy"),
        ]
        for pat, repl in patterns:
            new = re.sub(pat, repl, sabo, count=1, flags=re.I)
            if new != sabo:
                sabo = new
                what_changed = "Claimed accuracy far exceeding physical limits"
                break
        if not what_changed:
            sabo = sabo.rstrip(".") + ", achieving 99.99% classification accuracy with zero calibration."
            what_changed = "Appended unrealistic 99.99% accuracy claim"

    elif constraint_key == "adc_resolution":
        new = re.sub(r"(\d+)-bit", "8-bit", sabo, count=1, flags=re.I)
        if new != sabo:
            sabo = new
            what_changed = "Reduced ADC resolution to 8-bit, insufficient for uV-level signals"

    elif constraint_key == "data_bandwidth":
        new = re.sub(
            r"(wireless|bluetooth|BLE|Wi-?Fi)",
            r"\1 (requiring real-time streaming of all raw data at full bandwidth)",
            sabo, count=1, flags=re.I,
        )
        if new != sabo:
            sabo = new
            what_changed = "Added impossible real-time raw data streaming requirement"
        else:
            sabo = sabo.rstrip(".") + ". All raw data is streamed in real-time via Bluetooth LE at full resolution."
            what_changed = "Appended impossible BLE real-time streaming requirement"

    elif constraint_key == "power_budget":
        sabo = sabo.rstrip(".") + ". The system is powered by a single CR2032 coin cell for 72 hours of continuous operation."
        what_changed = "Appended impossible coin cell battery requirement"

    elif constraint_key == "sensor_bandwidth":
        new = re.sub(r"bandwidth\s*of\s*(\d+(?:\.\d+)?)\s*(?:Hz|kHz|MHz)", "bandwidth of 0.5 Hz", sabo, count=1, flags=re.I)
        if new != sabo:
            sabo = new
            what_changed = "Reduced sensor bandwidth to 0.5 Hz"

    elif constraint_key == "latency_constraint":
        sabo = sabo.rstrip(".") + ". The system achieves <0.1 ms total end-to-end latency including wireless transmission and cloud processing."
        what_changed = "Claimed impossible sub-ms latency including wireless and cloud"

    elif constraint_key == "temperature_range":
        sabo = sabo.rstrip(".") + ". The system operates reliably in outdoor conditions from -40C to +85C without thermal compensation."
        what_changed = "Claimed operation at extreme temperatures without thermal compensation"

    elif constraint_key == "snr_floor":
        new = re.sub(r"(?:preamplifier|pre-amp|amplifier|LNA)\s*", "", sabo, count=1, flags=re.I)
        if new != sabo:
            sabo = new
            what_changed = "Removed signal amplification"
        else:
            sabo = sabo.rstrip(".") + ". No preamplifier or electromagnetic shielding is used."
            what_changed = "Removed preamplifier and shielding"

    elif constraint_key == "optical_obstruction":
        new = re.sub(
            r"(sensor|optode|clip)\s*(is\s*)?(?:worn|placed|mounted|positioned)",
            r"\1 \2worn with a thick stainless steel watch underneath the \1,",
            sabo, count=1, flags=re.I,
        )
        if new != sabo:
            sabo = new
            what_changed = "Added metal watch in PPG optical path"

    if what_changed:
        return {
            "sabotaged_protocol": sabo,
            "what_changed": what_changed,
            "violated_principle": constraint_info["principle"],
            "why_invalid": f"This violates {constraint_info['principle']}. Example: {constraint_info['example_violation']}",
            "minimal_fix": f"Correct the modified parameter to satisfy {constraint_key} constraints",
        }
    return None


# ============================================================
# Pipeline phases (thread-safe, no global mutable state)
# ============================================================

def load_seed_data(seed_dir: str) -> tuple[list[dict], list[dict]]:
    """Load constraints.json and domains.json from seed directory."""
    constraints_path = os.path.join(seed_dir, "constraints.json")
    domains_path = os.path.join(seed_dir, "domains.json")

    if not os.path.exists(constraints_path):
        print(f"ERROR: {constraints_path} not found", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(domains_path):
        print(f"ERROR: {domains_path} not found", file=sys.stderr)
        sys.exit(1)

    with open(constraints_path, "r", encoding="utf-8") as f:
        constraints = json.load(f)
    with open(domains_path, "r", encoding="utf-8") as f:
        domains = json.load(f)

    print(f"Loaded {len(constraints)} constraints, {len(domains)} domains from {seed_dir}")
    return constraints, domains


def _generate_one_protocol(domain: dict, model_key: str, temperature: float) -> str | None:
    """Generate a single correct protocol (thread-safe)."""
    prompt = CORRECT_PROTOCOL_PROMPT.format(
        domain=domain["key"],
        description=domain["description"],
        sensors=", ".join(domain["sensors"]),
        signals=", ".join(domain["signals"]),
        typical_params=json.dumps(domain["typical_params"]),
    )
    content, _ = llm_call(
        "You are a biomedical engineering researcher writing valid experimental protocols.",
        prompt,
        model_key=model_key,
        temperature=temperature,
        max_tokens=1500,
    )
    return content.strip() if content else None


def _inject_one_sabotage(correct_protocol: str, constraint: dict, model_key: str) -> dict | None:
    """Inject sabotage into one protocol (thread-safe)."""
    prompt = SABOTAGE_INJECTION_PROMPT.format(
        constraint_name=constraint["key"],
        constraint_principle=constraint["principle"],
        example_violation=constraint["example_violation"],
        correct_protocol=correct_protocol,
    )
    result = llm_json_call(
        "You are a precise benchmark construction assistant. Output only valid JSON.",
        prompt,
        model_key=model_key,
        temperature=0.4,
        max_tokens=2000,
    )
    if result and "sabotaged_protocol" in result:
        return result
    return _rule_based_sabotage(correct_protocol, constraint["key"], constraint)


def _verify_one_item(sabotaged_protocol: str, violated_principle: str, why_invalid: str, model_key: str) -> dict:
    """Verify one benchmark item (thread-safe)."""
    prompt = VERIFIER_PROMPT.format(
        sabotaged_protocol=sabotaged_protocol[:1500],
        violated_principle=violated_principle,
        why_invalid=why_invalid,
    )
    result = llm_json_call(
        "You are a rigorous benchmark quality reviewer. Output only JSON.",
        prompt,
        model_key=model_key,
        temperature=0.2,
        max_tokens=800,
    )
    if result:
        return result
    return {
        "is_physically_wrong": True,
        "is_error_identifiable": True,
        "is_protocol_realistic": True,
        "obviousness": "moderate",
        "llm_would_fool": True,
        "quality_score": 3,
        "rejection_reason": None,
        "note": "verifier_failed_default_pass",
    }


def _generate_one_negative(domain: dict, label: str, model_key: str) -> dict | None:
    """Generate one valid or ambiguous protocol (thread-safe)."""
    if label == "valid":
        prompt = VALID_PROTOCOL_PROMPT.format(domain=domain["key"], description=domain["description"])
        system = "You are a biomedical engineering researcher. Write only valid, physically correct protocols."
    else:
        prompt = AMBIGUOUS_PROTOCOL_PROMPT.format(domain=domain["key"], description=domain["description"])
        system = "You are a biomedical engineering researcher. Write a protocol with one minor suboptimal issue."

    content, _ = llm_call(system, prompt, model_key=model_key, temperature=0.7, max_tokens=1500)
    if content:
        return {"protocol": content.strip(), "label": label}
    return None


# Difficulty assignment rules
DIFFICULTY_MAP = {
    "ematerial_block": "easy",
    "anatomical_misplacement": "easy",
    "optical_obstruction": "easy",
    "sampling_theorem": "medium",
    "sensor_bandwidth": "medium",
    "accuracy_impossibility": "hard",
    "power_budget": "hard",
    "data_bandwidth": "hard",
    "snr_floor": "hard",
    "latency_constraint": "hard",
    "adc_resolution": "hard",
    "temperature_range": "hard",
}


def assign_difficulty(constraint_key: str) -> str:
    return DIFFICULTY_MAP.get(constraint_key, "medium")


# ============================================================
# Main pipeline (concurrent)
# ============================================================

def run_pipeline(
    seed_dir: str = SEED_DATA_DIR,
    output_dir: str = OUTPUT_DIR,
    rounds: int = GENERATION_ROUNDS,
    protocols_per_domain: int = PROTOCOLS_PER_DOMAIN_PER_ROUND,
    sabotages_per_protocol: int = SABOTAGES_PER_PROTOCOL,
    model_key: str = None,
    temperatures: list[float] = None,
    concurrency: int = 8,
):
    """Run the full benchmark generation pipeline with concurrent API calls."""
    if temperatures is None:
        temperatures = GENERATION_TEMPERATURES

    os.makedirs(output_dir, exist_ok=True)

    # Phase 1: Load seed data
    constraints, domains = load_seed_data(seed_dir)
    model_cfg = get_model_config(model_key)
    model_name = model_cfg["model"]

    print("=" * 70)
    print("Hardware-Grounded Hallucination Benchmark Generator")
    print(f"  Model: {model_name}")
    print(f"  Rounds: {rounds}")
    print(f"  Protocols/domain/round: {protocols_per_domain}")
    print(f"  Sabotages/protocol: {sabotages_per_protocol}")
    print(f"  Domains: {len(domains)}")
    print(f"  Constraints: {len(constraints)}")
    print(f"  Concurrency: {concurrency}")
    print("=" * 70)

    all_items: list[dict] = []
    stats = {"generated": 0, "rule_passed": 0, "verifier_passed": 0}
    item_counter = 0
    start_time = time.time()

    for round_idx in range(rounds):
        temp = temperatures[round_idx % len(temperatures)]
        print(f"\n{'='*70}")
        print(f"ROUND {round_idx + 1}/{rounds}  (temperature={temp})")
        print(f"{'='*70}")

        # ── Phase 2: Generate correct protocols (parallel across domains) ──
        print(f"\n  Phase 2: Generating correct protocols (concurrency={concurrency})...")
        protocol_futures = {}
        with ThreadPoolExecutor(max_workers=concurrency) as pool:
            for domain in domains:
                for i in range(protocols_per_domain):
                    f = pool.submit(_generate_one_protocol, domain, model_key, temp)
                    protocol_futures[f] = (domain, i)

        domain_protocols: dict[str, list[str]] = {}
        for f in protocol_futures:
            domain, idx = protocol_futures[f]
            result = f.result()
            if result:
                domain_protocols.setdefault(domain["key"], []).append(result)

        total_protos = sum(len(v) for v in domain_protocols.values())
        print(f"    Generated {total_protos} correct protocols")

        # ── Phase 3+4+5: Sabotage injection + rule check + verification (parallel) ──
        # Build all (protocol, constraint) pairs
        sabotage_tasks = []
        for domain in domains:
            dk = domain["key"]
            applicable = [c for c in constraints if dk in c.get("domains", [])]
            selected = applicable[:sabotages_per_protocol]
            for correct_proto in domain_protocols.get(dk, []):
                for constraint in selected:
                    sabotage_tasks.append((domain, correct_proto, constraint))

        print(f"\n  Phase 3+4+5: {len(sabotage_tasks)} sabotage tasks (concurrency={concurrency})...")

        def _process_sabotage(task):
            domain, correct_proto, constraint = task
            dk = domain["key"]
            ck = constraint["key"]

            sabotage = _inject_one_sabotage(correct_proto, constraint, model_key)
            if not sabotage:
                return None

            # Rule check
            rule_results = run_checks(sabotage["sabotaged_protocol"], dk, ck)
            rule_passed = all(r.get("passed", True) for r in rule_results) if rule_results else True

            # LLM verification
            verifier = _verify_one_item(
                sabotage["sabotaged_protocol"],
                sabotage.get("violated_principle", constraint["principle"]),
                sabotage.get("why_invalid", ""),
                model_key,
            )
            quality = verifier.get("quality_score", 0)
            is_wrong = verifier.get("is_physically_wrong", False)
            is_realistic = verifier.get("is_protocol_realistic", False)
            verifier_passed = is_wrong and is_realistic and quality >= MIN_VERIFIER_QUALITY_SCORE

            return {
                "domain": domain,
                "constraint": constraint,
                "correct_proto": correct_proto,
                "sabotage": sabotage,
                "rule_results": rule_results,
                "rule_passed": rule_passed,
                "verifier": verifier,
                "verifier_passed": verifier_passed,
            }

        with ThreadPoolExecutor(max_workers=concurrency) as pool:
            futures = {pool.submit(_process_sabotage, t): t for t in sabotage_tasks}
            done = 0
            for f in as_completed(futures):
                done += 1
                result = f.result()
                if not result:
                    continue

                stats["generated"] += 1
                if result["rule_passed"]:
                    stats["rule_passed"] += 1
                if result["verifier_passed"]:
                    stats["verifier_passed"] += 1

                item_counter += 1
                domain = result["domain"]
                constraint = result["constraint"]
                sabotage = result["sabotage"]
                verifier = result["verifier"]

                difficulty = assign_difficulty(constraint["key"])
                plausibility = "high" if verifier.get("llm_would_fool") else "medium"

                item = make_item(
                    domain=domain["key"],
                    scenario=domain["description"],
                    label="fatal_violation",
                    protocol=sabotage["sabotaged_protocol"],
                    error_category=constraint["category"],
                    violated_constraint=constraint["key"],
                    violated_principle=sabotage.get("violated_principle", constraint["principle"]),
                    why_invalid=sabotage.get("why_invalid", ""),
                    minimal_fix=sabotage.get("minimal_fix", ""),
                    difficulty=difficulty,
                    surface_plausibility=plausibility,
                    severity=constraint.get("severity", "fatal"),
                    source_correct_protocol=result["correct_proto"],
                    what_changed=sabotage.get("what_changed", ""),
                    idx=item_counter,
                )
                item["_rule_passed"] = result["rule_passed"]
                item["_verifier_passed"] = result["verifier_passed"]
                item["_verifier_detail"] = verifier
                item["_rule_details"] = result["rule_results"]
                all_items.append(item)

                if done % 20 == 0 or done == len(futures):
                    elapsed = time.time() - start_time
                    print(f"    Progress: {done}/{len(futures)} sabotage tasks ({elapsed:.0f}s elapsed)", flush=True)

        # ── Phase 6: Negative samples (parallel across domains) ──
        n_valid = max(1, int(protocols_per_domain * VALID_RATIO))
        n_ambig = max(1, int(protocols_per_domain * AMBIGUOUS_RATIO))
        neg_tasks = []
        for domain in domains:
            for _ in range(n_valid):
                neg_tasks.append((domain, "valid"))
            for _ in range(n_ambig):
                neg_tasks.append((domain, "minor_issue"))

        print(f"\n  Phase 6: {len(neg_tasks)} negative samples (concurrency={concurrency})...")
        with ThreadPoolExecutor(max_workers=concurrency) as pool:
            futures = {pool.submit(_generate_one_negative, d, l, model_key): (d, l) for d, l in neg_tasks}
            for f in as_completed(futures):
                ns = f.result()
                if not ns:
                    continue
                domain, label = futures[f]
                item_counter += 1
                item = make_item(
                    domain=domain["key"],
                    scenario=domain["description"],
                    label=ns["label"],
                    protocol=ns["protocol"],
                    error_category="N/A" if ns["label"] == "valid" else "minor_issue",
                    violated_constraint="none" if ns["label"] == "valid" else "suboptimal",
                    violated_principle="",
                    why_invalid="" if ns["label"] == "valid" else "Minor suboptimal issue",
                    minimal_fix="",
                    difficulty="easy" if ns["label"] == "valid" else "medium",
                    surface_plausibility="high",
                    severity="none" if ns["label"] == "valid" else "minor",
                    source_correct_protocol="",
                    what_changed="",
                    idx=item_counter + 10000,
                )
                item["_rule_passed"] = True
                item["_verifier_passed"] = True
                all_items.append(item)

    # ============================================================
    # Phase 7: Filter, deduplicate, output
    # ============================================================
    elapsed_total = time.time() - start_time
    print(f"\n{'='*70}")
    print(f"Phase 7: Output  (total time: {elapsed_total:.0f}s)")
    print(f"{'='*70}")

    # Filter: keep items that pass verifier or rule check (or are negative samples)
    final_items = []
    for item in all_items:
        if item["label"] in ("valid", "minor_issue"):
            final_items.append(item)
        elif item.get("_verifier_passed", False):
            final_items.append(item)
        elif item.get("_rule_passed", False):
            final_items.append(item)

    # Deduplicate by protocol text
    seen_protocols: set[str] = set()
    deduped_items: list[dict] = []
    for item in final_items:
        key = item["protocol"][:200]
        if key not in seen_protocols:
            seen_protocols.add(key)
            deduped_items.append(item)

    print(f"  Before dedup: {len(final_items)}")
    print(f"  After dedup:  {len(deduped_items)}")

    # Compute stats
    label_counts: dict[str, int] = {}
    diff_counts: dict[str, int] = {}
    domain_counts: dict[str, int] = {}
    cat_counts: dict[str, int] = {}
    for item in deduped_items:
        label_counts[item["label"]] = label_counts.get(item["label"], 0) + 1
        diff_counts[item["difficulty"]] = diff_counts.get(item["difficulty"], 0) + 1
        domain_counts[item["domain"]] = domain_counts.get(item["domain"], 0) + 1
        cat_counts[item["error_category"]] = cat_counts.get(item["error_category"], 0) + 1

    print(f"  Labels:     {json.dumps(label_counts, ensure_ascii=False)}")
    print(f"  Difficulty: {json.dumps(diff_counts)}")
    print(f"  Domains:    {json.dumps(domain_counts)}")
    print(f"  Categories: {json.dumps(cat_counts, ensure_ascii=False)}")

    # Write benchmark.json
    clean_items = [make_clean_for_output(item) for item in deduped_items]
    benchmark_path = os.path.join(output_dir, "benchmark.json")
    with open(benchmark_path, "w", encoding="utf-8") as f:
        json.dump(clean_items, f, ensure_ascii=False, indent=2)
    print(f"\n  Saved {len(clean_items)} items to {benchmark_path}")

    # Write manifest.json
    manifest = {
        "generated_at": datetime.now().isoformat(),
        "model": model_name,
        "rounds": rounds,
        "protocols_per_domain": protocols_per_domain,
        "sabotages_per_protocol": sabotages_per_protocol,
        "temperatures": temperatures,
        "concurrency": concurrency,
        "seed_dir": seed_dir,
        "elapsed_seconds": round(elapsed_total),
        "stats": {
            "total_generated": stats["generated"],
            "rule_check_passed": stats["rule_passed"],
            "verifier_passed": stats["verifier_passed"],
            "after_dedup": len(deduped_items),
        },
        "label_distribution": label_counts,
        "difficulty_distribution": diff_counts,
        "domain_distribution": domain_counts,
        "category_distribution": cat_counts,
    }
    manifest_path = os.path.join(output_dir, "manifest.json")
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, ensure_ascii=False, indent=2)
    print(f"  Saved manifest to {manifest_path}")

    return clean_items, manifest


