"""Audit oracle-to-end-to-end Drop calculations for rebuttal.

The paper table rounds accuracies to one decimal place. If Drop is computed
from full-precision values and then rounded, it can differ by 0.1 percentage
points from subtracting the already rounded table cells. This script quantifies
that effect from the exported long result table.
"""

from __future__ import annotations

import argparse
import csv
import json
from collections import Counter
from pathlib import Path
from typing import Any


def pct(value: str) -> float:
    return float(value) * 100.0


def one_decimal(value: float) -> float:
    return round(value, 1)


def audit_rows(long_csv: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with long_csv.open(newline="", encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            for metric in ("three", "fine"):
                oracle = pct(row[f"stage2_oracle_{metric}_accuracy"])
                e2e = pct(row[f"stage2_end_to_end_{metric}_accuracy"])
                drop_full_precision = one_decimal(oracle - e2e)
                drop_from_displayed = one_decimal(one_decimal(oracle) - one_decimal(e2e))
                rows.append(
                    {
                        "dataset": row["dataset"],
                        "dataset_label": row["dataset_label"],
                        "model": row["model_label"],
                        "strategy": row["strategy_label"],
                        "metric": metric,
                        "oracle_accuracy_pct": oracle,
                        "e2e_accuracy_pct": e2e,
                        "oracle_display_pct": one_decimal(oracle),
                        "e2e_display_pct": one_decimal(e2e),
                        "drop_full_precision_pct": drop_full_precision,
                        "drop_from_displayed_pct": drop_from_displayed,
                        "rounding_delta_pct": one_decimal(
                            drop_full_precision - drop_from_displayed
                        ),
                    }
                )
    return rows


def write_csv(rows: list[dict[str, Any]], path: Path) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)


def write_markdown(rows: list[dict[str, Any]], path: Path) -> None:
    changed = [row for row in rows if row["rounding_delta_pct"] != 0.0]
    changed_by_metric = Counter(row["metric"] for row in changed)
    changed_by_dataset_metric = Counter((row["dataset"], row["metric"]) for row in changed)
    max_abs_delta = max(abs(row["rounding_delta_pct"]) for row in rows)

    examples = changed[:12]
    example_rows = "\n".join(
        "| {dataset_label} | {model} | {strategy} | {metric} | {oracle_display_pct:.1f} | "
        "{e2e_display_pct:.1f} | {drop_full_precision_pct:.1f} | "
        "{drop_from_displayed_pct:.1f} | {rounding_delta_pct:+.1f} |".format(**row)
        for row in examples
    )
    if not example_rows:
        example_rows = "| n/a | n/a | n/a | n/a | n/a | n/a | n/a | n/a | n/a |"

    text = f"""# Table Drop Audit

Generated by `scripts/audit_table_drop.py`.

## Definition Checked

For each run and Stage-2 metric, this audit compares:

- `drop_full_precision_pct`: `(oracle_accuracy - end_to_end_accuracy) * 100`,
  computed from full-precision exported values and then rounded to one decimal.
- `drop_from_displayed_pct`: the difference obtained after first rounding the
  Oracle and E2E table cells to one decimal and then subtracting them.

## Summary

| Item | Value |
|---|---:|
| Audited rows | {len(rows)} |
| Rows with nonzero rounding-order delta | {len(changed)} |
| Max absolute rounding-order delta | {max_abs_delta:.1f} percentage points |
| Three-class rows affected | {changed_by_metric.get('three', 0)} |
| Fine-12 rows affected | {changed_by_metric.get('fine', 0)} |
| Gold three-class rows affected | {changed_by_dataset_metric.get(('gold683', 'three'), 0)} |
| Gold Fine-12 rows affected | {changed_by_dataset_metric.get(('gold683', 'fine'), 0)} |
| Silver three-class rows affected | {changed_by_dataset_metric.get(('silver5k', 'three'), 0)} |
| Silver Fine-12 rows affected | {changed_by_dataset_metric.get(('silver5k', 'fine'), 0)} |

## Affected Examples

| Dataset | Model | Strategy | Metric | Oracle shown | E2E shown | Drop from full precision | Drop from shown cells | Delta |
|---|---|---|---|---:|---:|---:|---:|---:|
{example_rows}

## Rebuttal Note

The apparent slight mismatches are explained by rounding order. If the table
reports Oracle and E2E accuracies rounded to one decimal while Drop is computed
from full-precision values, subtracting the displayed cells can differ by at
most 0.1 percentage points. A camera-ready caption should state that Drop is
computed from full-precision Oracle and end-to-end accuracies before rounding.
"""
    path.write_text(text, encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--long-csv",
        type=Path,
        default=Path("experiments/main_20260510_main/tables/main_experiment_results_long.csv"),
    )
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=Path("experiments/rebuttal_20260708/table_drop_audit"),
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.output_dir.mkdir(parents=True, exist_ok=True)
    rows = audit_rows(args.long_csv)
    csv_path = args.output_dir / "table_drop_audit.csv"
    json_path = args.output_dir / "table_drop_audit.json"
    md_path = args.output_dir / "table_drop_audit.md"
    write_csv(rows, csv_path)
    json_path.write_text(json.dumps(rows, indent=2), encoding="utf-8")
    write_markdown(rows, md_path)
    print(f"Wrote {csv_path}")
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")


if __name__ == "__main__":
    main()
